"""Preserve the active Flash experience table and generate its native constants.

This reads literal integers only; it never executes ActionScript or TypeScript.
No original image, catalog or world/account save is modified.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path


SOURCE_FILES = {
    'BASE.as': 'client/scripts/BASE.as',
    'BFOUNDATION.as': 'client/scripts/BFOUNDATION.as',
    'BRESOURCE.as': 'client/scripts/BRESOURCE.as',
    'UI_TOP.as': 'client/scripts/UI_TOP.as',
    'PointsBar_882.as': 'client/scripts/SWC_ALL_fla/PointsBar_882.as',
    'experiencePoints.ts': 'server/src/game-data/stats/experiencePoints.ts',
    'calculateBaseLevel.ts': 'server/src/services/base/calculateBaseLevel.ts',
    'calculateEmpirePoints.ts': 'server/src/services/base/calculateEmpirePoints.ts',
}


def parse_integer_table(text: str, marker: str) -> list[int]:
    start = text.index(marker) + len(marker)
    value = text[start:text.index(']', start)]
    value = re.sub(r'//[^\r\n]*|/\*[\s\S]*?\*/', '', value)
    if not re.fullmatch(r'\s*\d+(?:\s*,\s*\d+)*\s*,?\s*', value):
        raise ValueError('Experience table must contain literal nonnegative integers only')
    result = [int(number.strip()) for number in value.split(',') if number.strip()]
    if not result or result[0] != 0 or any(a >= b for a, b in zip(result, result[1:])):
        raise ValueError('Experience thresholds must start at zero and increase strictly')
    if result[-1] > (1 << 53) - 1:
        raise ValueError('Experience threshold exceeds exact JSON integer precision')
    return result


def prepare_experience(source: Path, plugin: Path) -> dict:
    client = parse_integer_table((source / SOURCE_FILES['BASE.as']).read_text(encoding='utf-8-sig'),
                                 'private static const s_levels:Array = [')
    server = parse_integer_table((source / SOURCE_FILES['experiencePoints.ts']).read_text(encoding='utf-8-sig'),
                                 'export const experiencePoints: number[] = [')
    if len(client) != 100 or len(server) != 56 or client[:len(server)] != server:
        raise ValueError('The supplied active-client/server threshold discrepancy changed; review the source')
    data = plugin / 'Content/Data'
    originals = data / 'Original/Experience'
    originals.mkdir(parents=True, exist_ok=True)
    inputs = {}
    for name, relative in SOURCE_FILES.items():
        raw = (source / relative).read_bytes()
        (originals / name).write_bytes(raw)
        inputs[relative] = {'sha256': hashlib.sha256(raw).hexdigest(), 'bytes': len(raw)}
    result = {
        'schema': 1,
        'source': SOURCE_FILES['BASE.as'],
        'sourceFunction': 'BASE.BaseLevel, lines 4876-4905',
        'thresholds': client,
        'maximumDisplayedLevel': len(client) - 1,
        'finalThresholdIsUpperBoundary': True,
        'maximumExactInteger': (1 << 53) - 1,
        'suppliedServerThresholds': server,
        'sourceDiscrepancy': 'The active Flash client preserves 100 thresholds and displays levels 1-99; the supplied server helper truncates its copy to 56 thresholds. Native progression follows the active Flash client.',
        'sources': inputs,
    }
    (data / 'experience.json').write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
    constants = plugin / 'Source/BackyardMMO/Private/BYMExperienceThresholds.inl'
    constants.parent.mkdir(parents=True, exist_ok=True)
    constants.write_text('// Generated by Tools/prepare_experience.py from active BASE.s_levels.\n'
                         + '\n'.join('    ' + ', '.join(f'{value}LL' for value in client[offset:offset + 5]) + ','
                                     for offset in range(0, len(client), 5)) + '\n', encoding='utf-8')
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--plugin', type=Path, default=Path(__file__).resolve().parents[1] / 'Plugins/BackyardMMO')
    options = parser.parse_args()
    prepared = prepare_experience(options.source, options.plugin)
    print(f"Prepared {len(prepared['thresholds'])} original thresholds; maximum displayed level {prepared['maximumDisplayedLevel']}")
